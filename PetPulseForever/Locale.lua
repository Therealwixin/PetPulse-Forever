-- Exact UI phrases plus explicit dynamic prefixes; never translate client item text.
local prefixes={"Food priority: ","CRITICAL AMMO — ","LOW AMMO — ","Feed Pet Active — ","Nom nom...","Happy munching...","Snack time!","Munch, munch...","Tasty little break...","One more bite...","Cozy snack time...","Munchies!","Best buddy break..."}
function P.T(text)
    if type(text)~="string" then return text end
    local dict=translations[P.db and P.db.language]
    if not dict then return text end
    if dict[text] then return dict[text] end
    local companion=text:match("^(.-) is enjoying a meal$")
    if companion then return companion..dict[" is enjoying a meal"] end
    for _,prefix in ipairs(prefixes) do
        if text:sub(1,#prefix)==prefix then
            local tail=text:sub(#prefix+1)
            tail=tail:gsub(" LEFT$",dict[" LEFT"]):gsub("s Remaining$",dict["s Remaining"])
            return dict[prefix]..P.T(tail)
        end
    end
    return text
end
P.localizedLabels={}
function P.BindLabel(frame,text)
    P.localizedLabels[frame]=text;frame:SetText(P.T(text));return frame
end
function P.SetLanguage(lang)
    if lang~="EN" and not translations[lang] then return end
    P.db.language=lang
    for frame,text in pairs(P.localizedLabels) do frame:SetText(P.T(text)) end
    P.RefreshSettings();P.Paint();if P.guideWindow and P.guideWindow:IsShown() then P.RefreshGuideWindow() end
end
function P.LocalizeTooltip(tip)
    local addLine,addDouble=tip.AddLine,tip.AddDoubleLine
    tip.AddLine=function(self,text,...) return addLine(self,P.T(text),...) end
    tip.AddDoubleLine=function(self,left,right,...) return addDouble(self,P.T(left),P.T(right),...) end
end

